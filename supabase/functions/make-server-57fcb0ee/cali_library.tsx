// Aggregate + lookup helpers
// ---------------------------------------------------------------------------

export const EXERCISES: ReadonlyArray<Exercise> = Object.freeze([
  ...PUSH,
  ...PULL,
  ...CORE,
  ...LEGS,
  ...CONDITIONING,
  ...MOBILITY,
]);

// Build an id → exercise lookup once at module load.
const EXERCISE_BY_ID: ReadonlyMap<string, Exercise> = (() => {
  const m = new Map<string, Exercise>();
  const dupes: string[] = [];
  for (const ex of EXERCISES) {
    if (m.has(ex.id)) dupes.push(ex.id);
    m.set(ex.id, ex);
  }
  if (dupes.length > 0) {
    // This is a developer error — fail loudly so it's caught at deploy time.
    throw new Error(`[CALI-LIB] Duplicate exercise ids: ${dupes.join(", ")}`);
  }
  return m;
})();

console.log(
  `[CALI-LIB] Loaded ${EXERCISES.length} exercises (${LIBRARY_VERSION}) — ` +
    `push:${PUSH.length} pull:${PULL.length} core:${CORE.length} ` +
    `legs:${LEGS.length} cond:${CONDITIONING.length} mob:${MOBILITY.length}`,
);

export function getExercise(id: string): Exercise | undefined {
  return EXERCISE_BY_ID.get(id);
}

export function exercisesByCategory(cat: CaliCategory): Exercise[] {
  return EXERCISES.filter((e) => e.category === cat);
}
