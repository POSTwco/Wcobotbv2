/**
 * BOTB Calisthenics — Curated Exercise Library
 * =============================================
 *
 * Pure data, server-owned, versioned. The generator (cali.tsx, future slice)
 * selects from this list using a seeded RNG. A workout's `libraryVersion`
 * field is stored alongside its `seed` so the same workout can be
 * deterministically re-rendered later for auditing / anchor verification.
 *
 * VERSIONING RULES:
 *   - Bump LIBRARY_VERSION whenever any exercise is added, removed, OR has
 *     its `id`, `metric`, or `defaultDose` change. Pure cue/cosmetic edits
 *     do NOT require a bump (they don't affect reproducibility).
 *   - Never reuse an `id`. Deleted exercises stay removed; new variants get
 *     new ids. This protects historical workouts from silent drift.
 *
 * `level` is the MINIMUM workout level the exercise may appear in.
 *   L1 sessions select only L1 exercises.
 *   L2 sessions may select L1 or L2.
 *   L3 sessions may select any.
 *
 * `difficulty` (1..10) is a fine-grained selection weight WITHIN a level.
 *   The generator targets a difficulty band per block per level — e.g. an L1
 *   primary-push block targets difficulty 2-4, an L3 primary-push targets 6-9.
 *
 * `equipment` enumerates everything required. The generator filters by
 *   subset of the user's available-equipment profile field.
 *
 * NO PII, NO MEDIA URLS, NO USER DATA HERE. This file is loaded into every
 * edge isolate at boot — keep it lean.
 */

export const LIBRARY_VERSION = "cali-lib-1.2.0";

export type CaliCategory =
  | "push"
  | "pull"
  | "core"
  | "legs"
  | "conditioning"
  | "mobility";

export type CaliPattern =
  | "horizontal_push"
  | "vertical_push"
  | "horizontal_pull"
  | "vertical_pull"
  | "squat"
  | "lunge"
  | "hinge"
  | "anti_extension"
  | "anti_rotation"
  | "flexion"
  | "iso_hold"
  | "locomotion"
  | "plyo"
  | "stretch";

export type CaliMetric = "reps" | "time_sec";
export type CaliEquipmentReq = "none" | "bar" | "rings" | "wall";

export interface Exercise {
  id: string;
  name: string;
  category: CaliCategory;
  pattern: CaliPattern;
  /** Minimum workout level this exercise can appear in (1-3) */
  level: 1 | 2 | 3;
  /** Difficulty rating 1-10 — used for in-level selection weighting */
  difficulty: number;
  equipment: CaliEquipmentReq;
  unilateral: boolean;
  metric: CaliMetric;
  /**
   * Hint range the generator may use as a starting dose for this exercise.
   * The generator can override per block template (e.g. L3 push block bumps
   * the upper rep bound). [setsMin, setsMax, repsOrTimeMin, repsOrTimeMax].
   */
  defaultDose: [number, number, number, number];
  tempoHint?: string;
  /** 1-3 short coaching cues, < 80 chars each */
  cues: string[];
  /** Optional scaling references — generator does not auto-scale yet */
  scalingDown?: string;
  scalingUp?: string;
}

